import Foundation

/// Decides whether a pasteboard change may be stored. Runs on the type list and source alone,
/// before any payload is read or stored (spec: Privacy).
public struct CapturePolicy: Sendable {
    public var excludedBundleIDs: Set<String>

    /// Markers apps use to say "do not keep this" (nspasteboard.org and common password managers).
    /// Detection is imperfect: apps that do not mark their copies are not caught. Excluded apps cover the rest.
    public static let doNotKeepMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    /// Sensible starting exclusions. Nino can edit the list in Settings.
    public static let defaultExcludedApps: [String] = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    public enum Decision: Equatable, Sendable {
        case capture
        case skipOwnWrite
        case skipDoNotKeep
        case skipExcludedApp(String)
        case skipNothingSupported
    }

    public init(excludedBundleIDs: Set<String>) {
        self.excludedBundleIDs = excludedBundleIDs
    }

    /// - Parameters:
    ///   - types: every type on every pasteboard item.
    ///   - candidateSources: every app that could have made this copy (the frontmost app, apps
    ///     active in the last moment, the nspasteboard source). If any is excluded, skip. When
    ///     attribution is uncertain, err towards not capturing.
    public func decide(types: [String], candidateSources: [String]) -> Decision {
        if types.contains(PBType.internalMarker) { return .skipOwnWrite }
        if types.contains(where: { Self.doNotKeepMarkers.contains($0) }) { return .skipDoNotKeep }
        if let excluded = candidateSources.first(where: { excludedBundleIDs.contains($0) }) {
            return .skipExcludedApp(excluded)
        }
        if !types.contains(where: { PBType.supported.contains($0) }) { return .skipNothingSupported }
        return .capture
    }
}
